import { readdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const files = ['index.html', 'favicon.svg', 'favicon.ico', 'apple-touch-icon.png',
  'web-app-manifest-192x192.png', 'web-app-manifest-512x512.png',
  'energon-classic-logo.png', 'site.webmanifest', 'data/catalog.json'];
for (const directory of ['js', 'css']) {
  for (const name of (await readdir(path.join(root, directory))).sort()) {
    if (/\.(?:js|css)$/.test(name)) files.push(`${directory}/${name}`);
  }
}
const hash = createHash('sha256');
for (const file of [...files, 'sw.js']) hash.update(file).update(await readFile(path.join(root, file)));
const version = hash.digest('hex').slice(0, 16);
const source = `// Generated by scripts/build-offline.mjs. Regenerate after app changes.\nself.ORBIT_SHELL = ${JSON.stringify({version, files: ['./', ...files.map(file => `./${file}`)]}, null, 2)};\n`;
const target = path.join(root, 'offline-assets.js');
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8').catch(() => '') !== source) {
    console.error('Offline asset list is stale. Run node scripts/build-offline.mjs.');
    process.exitCode = 1;
  } else console.log(`Offline asset list current: ${files.length + 1} resources, ${version}`);
} else {
  await writeFile(target, source);
  console.log(`Offline asset list: ${files.length + 1} resources, ${version}`);
}
